export const t = (str, lang) => {
    if (lang === 'en' || !lang) return str;
    // Special handling for dynamic formats if needed
    if (!str) return str;

    // Replace if exact match
    if (translations[str]) return translations[str];

    // Dynamic translations
    if (typeof str === 'string') {
        if (str.startsWith('Add ')) {
            const item = str.replace('Add ', '');
            const translatedItem = translations[item] || item;
            return `הוספת ${translatedItem}`;
        }
        if (str.startsWith('Edit ')) {
            const item = str.replace('Edit ', '');
            const translatedItem = translations[item] || item;
            return `עריכת ${translatedItem}`;
        }

        let match = str.match(/^Product(\d+)$/i);
        if (match) return `מוצר ${match[1]}`;
        
        match = str.match(/^(.+) Supplier (\d+)$/i);
        if (match) return `ספק ${match[1]} ${match[2]}`;

        match = str.match(/^Supplier(\d+)$/i);
        if (match) return `ספק ${match[1]}`;
        
        match = str.match(/^([A-Za-z]+)\s*(\d+)$/);
        if (match) {
            const word = match[1];
            const num = match[2];
            const cap = word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
            const transWord = translations[word] || translations[cap] || word;
            return `${transWord} ${num}`;
        }
        
        if (str === 'Bakery') return 'מאפייה';
        if (str === 'Bread and Rolls') return 'לחם ולחמניות';
        if (str.includes('Supplier')) return str.replace('Supplier', 'ספק');
        if (str.includes('Product')) return str.replace('Product', 'מוצר');
    }

    // Replace partial matches for products if requested, or just return the string
    return str;
};
